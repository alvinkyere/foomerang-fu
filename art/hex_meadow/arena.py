"""The hex meadow's rules data (2026-11-06): writes games/foomerang-fu/src/rules/hexMeadowArena.ts from layout.json, rocks.json and
bamboo.json. World units are the plaza's (27.48 a plan unit); x east from plan X X0, y south from plan Y Y1.

  safeZone   the dashed border (layout.py): a player outside it for the config's limit explodes
  walls      the four rocks, as turned boxes (their fitted feet: ~0.92 of the superellipse's half sizes); the trees' trunks and the
             bamboo stalks as discs. The plants are not walls: players and boomerangs go through them, pushing them aside (the
             renderer's, render/hexPlants.ts; the HQ shows them hiding no one and stopping nothing)
  spawns     six inside the border, clear of the walls, spread apart; Book spots likewise

  python art/hex_meadow/arena.py       (from the repository root; the Python of art/audio/output/venv)
"""
import json, math
import numpy as np

S = 27.48
L = json.load(open('art/hex_meadow/layout.json'))
BORDER = L['border']
X0, X1, Y0, Y1 = BORDER['x0'] - 12, BORDER['x1'] + 12, BORDER['y0'] - 12, BORDER['y1'] + 12      # (12 units outside the border: the camera follows)
json.dump(dict(X0=X0, X1=X1, Y0=Y0, Y1=Y1, S=S, border=BORDER), open('art/hex_meadow/arena.json', 'w'))
w = lambda X, Y: (round((X - X0) * S), round((Y1 - Y) * S))
WIDTH, HEIGHT = round((X1 - X0) * S), round((Y1 - Y0) * S)
inside_arena = lambda X, Y: X0 < X < X1 and Y0 < Y < Y1

walls = []
for k, rk in enumerate(json.load(open('art/hex_meadow/rocks.json'))):
    x, y = w(rk['cx'], rk['cy'])
    walls.append(dict(id=f'ROCK_{k}', kind='WALL', shape='box', x=x, y=y, halfWidth=round(max(rk['w'] * 0.92 * S, 19)),
                      halfHeight=round(max(rk['d'] * 0.92 * S, 19)), angle=round(-math.radians(rk['yaw']), 4)))
# the trunks (~0.55 units round at the foot, blender/build.py) and the bamboo stalks (0.36): discs, at least the rules' least (18)
for k, t in enumerate(L['trees']):
    if inside_arena(*t['plan']):
        x, y = w(*t['plan']); walls.append(dict(id=f'TREE_{k}', kind='WALL', shape='disc', x=x, y=y, radius=max(18, round(0.55 * S))))
for k, b in enumerate(json.load(open('art/hex_meadow/bamboo.json'))):
    if inside_arena(*b['foot']):
        x, y = w(*b['foot']); walls.append(dict(id=f'BAMBOO_{k}', kind='WALL', shape='disc', x=x, y=y, radius=max(18, round(b['r'] * S))))


def clear(px, py, m):
    for o in walls:
        if o['shape'] == 'disc':
            if math.hypot(px - o['x'], py - o['y']) < o['radius'] + m: return False
            continue
        c, s_ = math.cos(o['angle']), math.sin(o['angle'])
        dx, dy = px - o['x'], py - o['y']
        lx, ly = abs(dx * c + dy * s_), abs(-dx * s_ + dy * c)
        if lx < o['halfWidth'] + m and ly < o['halfHeight'] + m: return False
    return True


bx0, bx1 = w(BORDER['x0'] + 3, 0)[0], w(BORDER['x1'] - 3, 0)[0]
by0, by1 = w(0, BORDER['y1'] - 3)[1], w(0, BORDER['y0'] + 3)[1]
cand = np.array([(x, y) for x in range(bx0, bx1, 20) for y in range(by0, by1, 20) if clear(x, y, 2.5 * S)], float)


def spread(n, seed):
    chosen = [cand[np.argmin(np.hypot(*(cand - seed).T))]]
    while len(chosen) < n:
        d = np.min([np.hypot(*(cand - c).T) for c in chosen], 0); chosen.append(cand[int(np.argmax(d))])
    return [dict(x=round(float(x), 1), y=round(float(y), 1)) for x, y in chosen]


spawns = spread(6, np.array([bx0, by0]))
books = spread(10, np.array([bx1, by1]))[4:]
sz = dict(x=w(BORDER['x0'], 0)[0], y=w(0, BORDER['y1'])[1], width=w(BORDER['x1'], 0)[0] - w(BORDER['x0'], 0)[0], height=w(0, BORDER['y0'])[1] - w(0, BORDER['y1'])[1])
obj = lambda d: '{ ' + ', '.join(f'{k}: ' + (f"'{v}'" if isinstance(v, str) else json.dumps(v)) for k, v in d.items()) + ' }'
ts = f"""import type {{ Vec2 }} from '@foomerang/game-core';
import type {{ FuArena, Rect, Solid }} from './arena';

/**
 * THE HEX MEADOW (`hex_meadow`): ff physics hq 2.mp4 20:02 (art/hex_meadow). A lime meadow inside a dashed border, filled with fields
 * of hexagonal plants on stems, gold trees with lavender trunks, four lavender rocks and bamboo. The rocks, the trunks and the bamboo
 * are solid; a player outside the border for the config's limit explodes. The plants are no walls: they are pushed aside and burn
 * (drawn only: apps/console/src/render/hexPlants.ts).
 *
 * GENERATED by art/hex_meadow/arena.py from art/hex_meadow/layout.json: do not edit by hand.
 */

export const HEX_MEADOW_WIDTH = {WIDTH};
export const HEX_MEADOW_HEIGHT = {HEIGHT};

export type HexMeadowWall = Solid & {{ readonly id: string; readonly kind: 'WALL' }};

export const HEX_MEADOW_WALLS: readonly HexMeadowWall[] = Object.freeze([
{''.join('  Object.freeze(' + obj(o) + '),\n' for o in walls)}]);

export const HEX_MEADOW_SAFE_ZONE: Rect = Object.freeze({json.dumps(sz).replace('"', '')});

export const HEX_MEADOW_SPAWNS: readonly Vec2[] = Object.freeze([
{''.join('  ' + obj(o) + ',\n' for o in spawns)}]);

export const HEX_MEADOW_BOOK_SPOTS: readonly Vec2[] = Object.freeze([
{''.join('  ' + obj(o) + ',\n' for o in books)}]);

export const HEX_MEADOW_ARENA: FuArena = Object.freeze({{
  width: HEX_MEADOW_WIDTH,
  height: HEX_MEADOW_HEIGHT,
  walls: HEX_MEADOW_WALLS,
  spawns: HEX_MEADOW_SPAWNS,
  safeZone: HEX_MEADOW_SAFE_ZONE,
}});
"""
open('games/foomerang-fu/src/rules/hexMeadowArena.ts', 'w').write(ts)
print('arena', WIDTH, 'x', HEIGHT, ';', len(walls), 'walls, safe zone', sz, ', spawns', len(spawns))
