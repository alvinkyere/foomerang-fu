"""The autumn glade's rules data (2026-11-01): writes games/foomerang-fu/src/rules/autumnGladeArena.ts from layout.json. World units are
the plaza's (27.48 a plan unit); x east from plan X X0, y south from plan Y Y1.

  safeZone   the dashed border (measure.py: x -25.4..30.2, y -20.68..18.69): a player outside it for the config's limit explodes
  walls      the three logs and the two rocks, as turned boxes (a log is a 0.65-radius cylinder, a rock its foot as blender/build.py has it)
  spawns     six inside the border, clear of the walls, spread apart; Book spots likewise

  python art/autumn_glade/arena.py       (from the repository root; the Python of art/audio/output/venv)
"""
import json, math
import numpy as np

S = 27.48
BORDER = dict(x0=-25.4, x1=30.2, y0=-20.68, y1=18.69)      # (measure.py: the dashed rectangle in plan units)
X0, X1, Y0, Y1 = -38.0, 43.0, -33.0, 31.0                  # (12 units of sand outside the border: players may cross it, the camera follows)
json.dump(dict(X0=X0, X1=X1, Y0=Y0, Y1=Y1, S=S, border=BORDER), open('art/autumn_glade/arena.json', 'w'))
L = json.load(open('art/autumn_glade/layout.json'))
w = lambda X, Y: (round((X - X0) * S), round((Y1 - Y) * S))
WIDTH, HEIGHT = round((X1 - X0) * S), round((Y1 - Y0) * S)
LOG_R = 0.65      # (the collider is at least 38 wide: the rules refuse a wall thinner than a player, 36)


LOGS = json.load(open('art/autumn_glade/logs.json'))[:2] + [dict(ends=L['log3']['ends'], r=0.62)]      # (fit_logs.py)
walls = []
for k, lg in enumerate(LOGS):
    (ax, ay), (bx, by) = lg['ends']
    cx, cy = w((ax + bx) / 2, (ay + by) / 2)
    walls.append(dict(id=f'LOG_{k}', kind='WALL', shape='box', x=cx, y=cy, halfWidth=round(math.hypot(bx - ax, by - ay) / 2 * S),
                      halfHeight=round(max(lg['r'] * S, 19)), angle=round(-math.atan2(by - ay, bx - ax), 4)))
for r_ in json.load(open('art/autumn_glade/rocks.json')):      # (fit_rocks.py: each block's foot is its superellipse outline: about 0.92 of its half sizes)
    for i, b_ in enumerate(r_['blocks']):
        x, y = w(b_['cx'], b_['cy'])
        walls.append(dict(id=f"ROCK_{r_['side']}_{i}", kind='WALL', shape='box', x=x, y=y, halfWidth=round(max(b_['w'] * 0.92 * S, 19)), halfHeight=round(max(b_['d'] * 0.92 * S, 19)), angle=0))

# portal pads (portals.ts): a disc on the sand in front of each portal (props.py 'portals': the glow's centre), each sending to the other
pads = []
for i, p_ in enumerate(L['portals']):
    x, y = w(*p_['glow'])
    pads.append(dict(id=f'PORTAL_{i}', x=x, y=y, radius=round(S), to=f'PORTAL_{1 - i}'))

# spawns and Book spots: inside the border by 3 units, 2.5 units from any wall and from the pads, farthest-point spread
def clear(px, py, m):
    for o in walls:
        c, s_ = math.cos(o['angle']), math.sin(o['angle'])
        dx, dy = px - o['x'], py - o['y']
        lx, ly = abs(dx * c + dy * s_), abs(-dx * s_ + dy * c)
        if lx < o['halfWidth'] + m and ly < o['halfHeight'] + m: return False
    return True
bx0, bx1 = w(BORDER['x0'] + 3, 0)[0], w(BORDER['x1'] - 3, 0)[0]
by0, by1 = w(0, BORDER['y1'] - 3)[1], w(0, BORDER['y0'] + 3)[1]
cand = np.array([(x, y) for x in range(bx0, bx1, 20) for y in range(by0, by1, 20) if clear(x, y, 2.5 * S) and all(math.hypot(x - q['x'], y - q['y']) > 3.5 * S for q in pads)], float)
def spread(n, seed):
    chosen = [cand[np.argmin(np.hypot(*(cand - seed).T))]]
    while len(chosen) < n:
        d = np.min([np.hypot(*(cand - c).T) for c in chosen], 0); chosen.append(cand[int(np.argmax(d))])
    return [dict(x=round(float(x), 1), y=round(float(y), 1)) for x, y in chosen]
spawns = spread(6, np.array([bx0, by0]))
books = spread(10, np.array([bx1, by1]))[4:]
sz = dict(x=w(BORDER['x0'], 0)[0], y=w(0, BORDER['y1'])[1], width=w(BORDER['x1'], 0)[0] - w(BORDER['x0'], 0)[0], height=w(0, BORDER['y0'])[1] - w(0, BORDER['y1'])[1])

obj = lambda d: '{ ' + ', '.join(f'{k}: ' + (f"'{v}'" if isinstance(v, str) else json.dumps(v)) for k, v in d.items()) + ' }'
ts = f"""import type {{ Vec2 }} from '@foomerang/game-core';
import type {{ FuArena, Rect, Solid }} from './arena';
import type {{ ArenaPortal }} from './portals';

/**
 * THE AUTUMN GLADE (`autumn_glade`): ff physics hq 2.mp4 10:26 (art/autumn_glade). A golden clearing with a dashed border, red and
 * gold trees, three logs and two rocks with portals. The logs and the rocks are solid; a player outside the border for the config's
 * limit explodes. The trees are not solid (the frame shows players behind their canopies); the portals' pads teleport a player or a boomerang to the other.
 *
 * GENERATED by art/autumn_glade/arena.py from art/autumn_glade/layout.json: do not edit by hand.
 */

export const AUTUMN_GLADE_WIDTH = {WIDTH};
export const AUTUMN_GLADE_HEIGHT = {HEIGHT};

export type AutumnGladeWall = Solid & {{ readonly id: string; readonly kind: 'WALL' }};

export const AUTUMN_GLADE_WALLS: readonly AutumnGladeWall[] = Object.freeze([
{''.join('  Object.freeze(' + obj(o) + '),\n' for o in walls)}]);

export const AUTUMN_GLADE_SAFE_ZONE: Rect = Object.freeze({json.dumps(sz).replace('"', '')});

export const AUTUMN_GLADE_PORTALS: readonly ArenaPortal[] = Object.freeze([
{''.join('  Object.freeze(' + obj(o) + '),\n' for o in pads)}]);

export const AUTUMN_GLADE_SPAWNS: readonly Vec2[] = Object.freeze([
{''.join('  ' + obj(o) + ',\n' for o in spawns)}]);

export const AUTUMN_GLADE_BOOK_SPOTS: readonly Vec2[] = Object.freeze([
{''.join('  ' + obj(o) + ',\n' for o in books)}]);

export const AUTUMN_GLADE_ARENA: FuArena = Object.freeze({{
  width: AUTUMN_GLADE_WIDTH,
  height: AUTUMN_GLADE_HEIGHT,
  walls: AUTUMN_GLADE_WALLS,
  spawns: AUTUMN_GLADE_SPAWNS,
  portals: AUTUMN_GLADE_PORTALS,
  safeZone: AUTUMN_GLADE_SAFE_ZONE,
}});
"""
open('games/foomerang-fu/src/rules/autumnGladeArena.ts', 'w').write(ts)
print('arena', WIDTH, 'x', HEIGHT, ';', len(walls), 'walls, safe zone', sz, ', spawns', len(spawns))
