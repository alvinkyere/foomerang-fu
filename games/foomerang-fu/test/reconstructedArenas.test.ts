describe.each(CASES)('$name: the arena data', ({ arena, walls: data, spawns, books, kinds }) => {
  const walls = wallsOf(arena);
  const WIDTH = arena.width;
  const HEIGHT = arena.height;
  it('six spawns, only blocking obstacles of the generated kinds, and no Slice 6 systems', () => {
    expect(arena.spawns).toHaveLength(6);
    expect(arena.gates ?? []).toEqual([]);
    expect(arena.platforms ?? []).toEqual([]);
    expect(arena.hazards ?? []).toEqual([]);
    expect(walls).toHaveLength(data.length);
    expect(new Set(data.map((w) => w.kind))).toEqual(new Set(kinds));
    expect(createFuMatch([{ id: 'a', slot: 0 }], { arena }).config.arena).toBe(arena);
  });

  it('every obstacle lies inside the boundary, has a positive size and a unique id', () => {
    expect(new Set(data.map((w) => w.id)).size).toBe(data.length);
    for (const w of walls) {
      expect(w.width).toBeGreaterThan(0);
      expect(w.height).toBeGreaterThan(0);
      expect(w.x).toBeGreaterThanOrEqual(0);
      expect(w.y).toBeGreaterThanOrEqual(0);
      expect(w.x + w.width).toBeLessThanOrEqual(WIDTH);
      expect(w.y + w.height).toBeLessThanOrEqual(HEIGHT);
    }
  });

  it('every spawn and Book spot is on open floor with room around it; spawns are well spread', () => {
    for (const p of [...spawns, ...books]) {
      expect(circleHitsWalls(p, R + 20, walls), `${p.x},${p.y}`).toBe(false);
      expect(p.x - R).toBeGreaterThan(0);
      expect(p.y - R).toBeGreaterThan(0);
      expect(p.x + R).toBeLessThan(WIDTH);
      expect(p.y + R).toBeLessThan(HEIGHT);
    }
    for (let i = 0; i < 6; i += 1)
      for (let j = i + 1; j < 6; j += 1) {
        const a = spawns[i];
        const b = spawns[j];
        expect(Math.hypot((a?.x ?? 0) - (b?.x ?? 0), (a?.y ?? 0) - (b?.y ?? 0))).toBeGreaterThan(
          300,
        );
      }
  });

  it('six-player fuzz with the approved mechanics never puts a living body inside an obstacle or outside the boundary', () => {
    const IDS = ['a', 'b', 'c', 'd', 'e', 'f'];
    let s = make(IDS, { arena, ...FREE_FOR_ALL, seed: 11 });
    for (let i = 0; i < 2400; i += 1) {
      s = stepFu(
        s,
        input(
          Object.fromEntries(
            IDS.map((id, k) => [
              id,
              {
                move: { x: Math.cos(i / (11 + 2 * k) + k), y: Math.sin(i / (13 + k) + 2 * k) },
                dash: (i + 3 * k) % 17 === 0,
                throw: (i + 5 * k) % 37 === 0,
                slash: (i + 2 * k) % 41 === 0,
              },
            ]),
          ),
        ),
        DT,
      ).state;
      for (const p of s.players) {
        if (!p.alive) continue;
        const pos = at(s, p.id);
        expect(circleHitsWalls(pos, R - 0.01, walls), `tick ${i} ${p.id}`).toBe(false);
        expect(pos.x).toBeGreaterThanOrEqual(R - 1e-6);
        expect(pos.y).toBeGreaterThanOrEqual(R - 1e-6);
        expect(pos.x).toBeLessThanOrEqual(WIDTH - R + 1e-6);
        expect(pos.y).toBeLessThanOrEqual(HEIGHT - R + 1e-6);
      }
    }
  });
});
